import { createHash } from "node:crypto";
import { readFile, writeFile } from "node:fs/promises";
import { resolve } from "node:path";
import { fileURLToPath } from "node:url";

const repositoryRoot = resolve(fileURLToPath(new URL("..", import.meta.url)));
const inputPath = resolve(
  repositoryRoot,
  process.argv[2] ?? "data/cosmetic_small_molecules_pubchem.csv",
);
const outputPath = resolve(
  repositoryRoot,
  process.argv[3] ?? "lib/evidence/chinese-compounds.generated.ts",
);

function parseCsv(text) {
  const rows = [];
  let row = [];
  let field = "";
  let quoted = false;

  for (let index = 0; index < text.length; index += 1) {
    const character = text[index];
    if (quoted) {
      if (character === '"' && text[index + 1] === '"') {
        field += '"';
        index += 1;
      } else if (character === '"') {
        quoted = false;
      } else {
        field += character;
      }
    } else if (character === '"') {
      quoted = true;
    } else if (character === ",") {
      row.push(field);
      field = "";
    } else if (character === "\n") {
      row.push(field.replace(/\r$/u, ""));
      rows.push(row);
      row = [];
      field = "";
    } else {
      field += character;
    }
  }

  if (quoted) throw new Error("CSV contains an unterminated quoted field.");
  if (field || row.length) {
    row.push(field.replace(/\r$/u, ""));
    rows.push(row);
  }
  return rows;
}

function normalizedIdentifier(value) {
  return value.normalize("NFKC").trim().toLocaleLowerCase("zh-CN");
}

function assertUnique(map, key, description, lineNumber) {
  const priorLine = map.get(key);
  if (priorLine !== undefined) {
    throw new Error(
      `Duplicate ${description} at CSV lines ${priorLine} and ${lineNumber}.`,
    );
  }
  map.set(key, lineNumber);
}

const source = await readFile(inputPath, "utf8");
const parsed = parseCsv(source.replace(/^\uFEFF/u, ""));
const expectedHeaders = ["中文名称", "英文全称", "PubChem CID"];
const headers = parsed.shift();
if (
  !headers ||
  headers.length !== expectedHeaders.length ||
  headers.some((header, index) => header.trim() !== expectedHeaders[index])
) {
  throw new Error(
    `Expected CSV headers ${expectedHeaders.join(",")}; received ${headers?.join(",") ?? "none"}.`,
  );
}

const chineseNames = new Map();
const englishNames = new Map();
const pubchemCids = new Map();
const entries = parsed
  .filter((row) => row.some((field) => field.trim()))
  .map((row, index) => {
    const lineNumber = index + 2;
    if (row.length !== 3) {
      throw new Error(
        `Expected 3 fields at CSV line ${lineNumber}; received ${row.length}.`,
      );
    }
    const [labelZhRaw, englishNameRaw, cidRaw] = row;
    const labelZh = labelZhRaw.trim();
    const englishName = englishNameRaw.trim();
    const cid = Number(cidRaw.trim());
    if (!labelZh || !englishName || !Number.isSafeInteger(cid) || cid <= 0) {
      throw new Error(
        `Invalid Chinese name, English name, or PubChem CID at CSV line ${lineNumber}.`,
      );
    }

    assertUnique(
      chineseNames,
      normalizedIdentifier(labelZh),
      `Chinese name "${labelZh}"`,
      lineNumber,
    );
    assertUnique(
      englishNames,
      normalizedIdentifier(englishName),
      `English name "${englishName}"`,
      lineNumber,
    );
    assertUnique(pubchemCids, String(cid), `PubChem CID ${cid}`, lineNumber);
    return { labelZh, englishName, cid };
  });

const checksum = createHash("sha256").update(source).digest("hex");
const renderedEntries = entries
  .map(
    (entry) =>
      `  { labelZh: ${JSON.stringify(entry.labelZh)}, englishName: ${JSON.stringify(entry.englishName)}, cid: ${entry.cid}, source: "cosmetic-small-molecules-pubchem-csv" },`,
  )
  .join("\n");
const output = `// Generated by scripts/generate-chinese-compound-data.mjs.
// Source: data/cosmetic_small_molecules_pubchem.csv
// SHA-256: ${checksum}
// Do not edit this file by hand; update the CSV and rerun the generator.

export const GENERATED_CHINESE_COMPOUND_ENTRIES = [
${renderedEntries}
] as const;
`;

await writeFile(outputPath, output, "utf8");
console.log(
  `Generated ${entries.length} Chinese compound entries at ${outputPath}.`,
);
